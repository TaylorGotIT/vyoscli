#!/usr/bin/env python3
"""Build a vyoscli .ipk without the OpenWrt SDK.

vyoscli is pure Python with ``PKGARCH:=all``: the SDK only orchestrates
packaging (no compile step), so the ipk can be produced on any host. Use this
to smoke-test a build on a device quickly; use the SDK (scripts/build-ipk.sh)
for release artefacts, where opkg/Apk metadata must be generated by the
toolchain.

    python3 scripts/make-ipk.py            # -> dist/vyoscli_0.2.0-r1_all.ipk
    python3 scripts/make-ipk.py --minimal-deps

Format: an ar archive holding debian-binary, control.tar.gz, data.tar.gz.
"""

from __future__ import annotations

import argparse
import gzip
import io
import os
import re
import stat
import sys
import tarfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PKG = REPO / "package" / "vyoscli"
FILES = PKG / "files"
MAKEFILE = PKG / "Makefile"

ESSENTIAL_DEPS = ["libc", "python3", "python3-readline", "ip-full"]


def read_makefile() -> dict:
    text = MAKEFILE.read_text(encoding="utf-8")
    fields = {}
    for key, pattern in {
        "version": r"^PKG_VERSION:=(.+)$",
        "release": r"^PKG_RELEASE:=(.+)$",
        "license": r"^PKG_LICENSE:=(.+)$",
        "maintainer": r"^PKG_MAINTAINER:=(.+)$",
        "depends": r"DEPENDS:=(.+)$",
    }.items():
        m = re.search(pattern, text, re.M)
        fields[key] = m.group(1).strip() if m else ""
    m = re.search(r"URL:=(.+)$", text, re.M)
    fields["url"] = m.group(1).strip() if m else ""
    m = re.search(r"TITLE:=(.+)$", text, re.M)
    fields["title"] = m.group(1).strip() if m else "vyoscli"
    m = re.search(r"define Package/vyoscli/description\n(.*?)\nendef", text, re.S)
    fields["description"] = (m.group(1).strip() if m else fields["title"])
    return fields


def deps_from_makefile(raw: str) -> list[str]:
    deps = []
    for token in raw.split():
        if token.startswith("+"):
            deps.append(token[1:])
        elif token.startswith("@"):
            continue
    return deps


def iter_payload():
    """Yield (arcname, path, mode) for every file under files/."""
    executable = {"usr/bin/vyoscli", "etc/init.d/vyoscli"}
    for path in sorted(FILES.rglob("*")):
        rel = path.relative_to(FILES).as_posix()
        if "__pycache__" in rel or rel.endswith(".pyc"):
            continue
        arcname = "./" + rel
        if path.is_dir():
            yield arcname, path, 0o755
            continue
        yield arcname, path, 0o755 if rel in executable else 0o644


def add_tree(tar: tarfile.TarFile) -> None:
    seen_dirs = set()

    def add_dir(name: str, mtime: int) -> None:
        name = name.rstrip("/")
        if not name or name == ".":
            name = "./"
        if name in seen_dirs:
            return
        info = tarfile.TarInfo(name)
        info.type = tarfile.DIRTYPE
        info.mode = 0o755
        info.uid = info.gid = 0
        info.uname = info.gname = "root"
        info.mtime = mtime
        tar.addfile(info)
        seen_dirs.add(name)

    mtime = int(os.environ.get("SOURCE_DATE_EPOCH", "0")) or int(time.time())
    add_dir("./", mtime)
    for arcname, path, mode in iter_payload():
        if path.is_dir():
            add_dir(arcname, mtime)
            continue
        parent = arcname.rsplit("/", 1)[0]
        parts = parent.split("/")
        for i in range(2, len(parts) + 1):
            add_dir("/".join(parts[:i]), mtime)
        info = tarfile.TarInfo(arcname)
        info.mode = mode
        info.uid = info.gid = 0
        info.uname = info.gname = "root"
        info.mtime = mtime
        data = path.read_bytes()
        info.size = len(data)
        tar.addfile(info, io.BytesIO(data))


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def control_text(fields: dict, deps: list[str], installed_kb: int) -> str:
    desc = fields["description"].splitlines()
    description = "Description: " + desc[0] if desc else "Description: vyoscli"
    for line in desc[1:]:
        description += "\n " + line
    return "\n".join([
        "Package: vyoscli",
        f"Version: {fields['version']}-r{fields['release']}",
        f"Depends: {', '.join(deps)}",
        "Source: feeds/base/utils/vyoscli",
        "SourceName: vyoscli",
        f"License: {fields['license']}",
        "Section: utils",
        "Architecture: all",
        f"Installed-Size: {installed_kb}",
        f"Maintainer: {fields['maintainer']}",
        f"URL: {fields['url']}",
        description,
        "",
    ])


def postinst() -> str:
    return "\n".join([
        "#!/bin/sh",
        '[ -n "$IPKG_INSTROOT" ] || {',
        "\t/etc/init.d/vyoscli enable 2>/dev/null",
        "}",
        "exit 0",
        "",
    ])


def tar_gz(entries: list[tuple[str, bytes, int]]) -> bytes:
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w") as tar:
        for name, data, mode in entries:
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = mode
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mtime = 0
            tar.addfile(info, io.BytesIO(data))
    return gz(raw.getvalue())


def outer_pkg(control_bytes: bytes, data_bytes: bytes) -> bytes:
    """OpenWrt ipk = gzipped tar holding debian-binary + control + data.

    (Not Debian's ar format: `ipkg-build` in OpenWrt packs a tar.gz of these
    three members, and that is what official 24.10 .ipk files look like.)
    """
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w") as tar:
        for name, data in (("./debian-binary", b"2.0\n"),
                           ("./data.tar.gz", data_bytes),
                           ("./control.tar.gz", control_bytes)):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = "root"
            info.mtime = 0
            tar.addfile(info, io.BytesIO(data))
    return gz(raw.getvalue())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(REPO / "dist"), help="output directory")
    ap.add_argument("--minimal-deps", action="store_true",
                    help="only ship the hard requirements (for quick device tests)")
    args = ap.parse_args()

    fields = read_makefile()
    deps = deps_from_makefile(fields["depends"])
    if args.minimal_deps:
        deps = list(ESSENTIAL_DEPS)
    elif "libc" not in deps:
        deps.insert(0, "libc")

    data_raw = io.BytesIO()
    with tarfile.open(fileobj=data_raw, mode="w") as tar:
        add_tree(tar)
    installed_bytes = sum(path.stat().st_size
                          for _, path, _ in iter_payload() if path.is_file())

    control = tar_gz([("./control",
                       control_text(fields, deps, max(1, installed_bytes // 1024)).encode(),
                       0o644),
                      ("./postinst", postinst().encode(), 0o755)])
    data = gz(data_raw.getvalue())
    ipk = outer_pkg(control, data)

    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)
    name = f"vyoscli_{fields['version']}-r{fields['release']}_all.ipk"
    target = outdir / name
    target.write_bytes(ipk)
    print(f"wrote {target} ({len(ipk)} bytes, {len(deps)} deps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
